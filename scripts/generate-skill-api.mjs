// Writes the API reference of the lost-ui skill from the code: skills/lost-ui/references/api/<layer>.md
// and the catalog. The props are what each component declares itself (the HTML attributes it passes
// through are left out), with the description and the default from the code.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { withCustomConfig } from "react-docgen-typescript";

const layers = {
  elements: "src/components/elements",
  app: "src/components/app",
  "ai-chat": "src/components/ai-chat",
  editor: "src/components/editor",
  calendar: "src/components/calendar",
  forms: "src/components/forms",
  data: "src/components/data",
  charts: "src/components/charts",
  templates: "src/templates",
};
const catalogOnly = {
  ui: "src/components/ui",
};
const notes = {
  ui: "shadcn primitives, upstream shape (props are the Radix and HTML ones). Peers by path: calendar, carousel, command, drawer, form, input-otp, resizable, sonner.",
  elements: "small pieces made of primitives.",
  app: "the frame of an app. `app` needs `sonner` and is imported by path (`@danielsoaresf/lost-ui/app/app`). `app-nav` has the `NavItem` types and helpers, no component.",
  "ai-chat":
    "the pieces of an AI chat screen. No SDK needed: messages have the shape of the Vercel AI SDK `UIMessage`, so `useChat().messages` goes in as it is. See `references/ai-chat.md`.",
  editor:
    "a Notion-style block editor on Tiptap (`/` menu, selection toolbar, block handle, tables, tasks, callouts, toggles). Needs the Tiptap peers; see `references/editor.md`.",
  calendar:
    "month, week and day views of events (`EventCalendar` is the whole screen), a list of calendars to show or hide, and the date helpers. No peers. See `references/calendar.md`.",
  forms:
    "`form-input-date`, `form-pin-input`, `form-input-phone`, `form-country-select`, `form-emoji-picker` and `form-builder` need optional peers and are imported by path.",
  data: "data display.",
  charts: "`*-chart` are the data-driven ones; the other folders are the pieces they are made of.",
  templates:
    "pages and layouts reused between projects, grouped by category (`auth`, `errors`, `backoffice`): import `@danielsoaresf/lost-ui/templates/<category>/<folder>`. `lib` holds helpers, not for import.",
};

const parser = withCustomConfig("tsconfig.json", {
  savePropValueAsString: true,
  shouldExtractLiteralValuesFromEnum: false,
  shouldRemoveUndefinedFromOptional: true,
  propFilter: (prop) => {
    const from = prop.declarations ?? [];
    // keep what the library declares; drop the HTML attributes and the Radix props it passes through
    return from.length === 0 || from.some((d) => !d.fileName.includes("node_modules"));
  },
});

const cell = (text, max = 110) => {
  const flat = String(text ?? "")
    .replace(/\s+/g, " ")
    .replace(/\|/g, "\\|")
    .trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
};

const folders = (dir) =>
  readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name !== "lib" && existsSync(`${dir}/${e.name}/index.ts`))
    .map((e) => e.name)
    .sort();

// the templates are grouped by category (`auth/login-page`), the other layers are flat
const entries = (layer, dir) =>
  layer === "templates"
    ? folders(dir).flatMap((category) =>
        folders(`${dir}/${category}`).map((name) => `${category}/${name}`),
      )
    : folders(dir);

mkdirSync("skills/lost-ui/references/api", { recursive: true });

let catalog =
  "# Catalog\n\nEvery folder is importable as `@danielsoaresf/lost-ui/<layer>/<folder>`; the layer entry (`@danielsoaresf/lost-ui/<layer>`) exports all of them except the ones noted. Generated by `npm run skill`; the props of each component are in `api/<layer>.md`.\n\n";

for (const [layer, dir] of Object.entries({ ...catalogOnly, ...layers })) {
  const names = entries(layer, dir);
  catalog += `## ${layer} (\`@danielsoaresf/lost-ui/${layer}\`)\n\n${notes[layer]}\n\n${names.map((n) => `\`${n}\``).join(", ")}\n\n`;
}
const effects = readdirSync("src/components/effects", { withFileTypes: true }).filter((e) =>
  e.isDirectory(),
).length;
catalog += `## effects (\`@danielsoaresf/lost-ui/effects\`)\n\n${effects} landing-page animations from Magic UI (marquee, globe, confetti, blur-fade, number-ticker…). Names, paths and optional peers: the library's \`docs/effects-inventory.md\`.\n\n## i18n (\`@danielsoaresf/lost-ui/i18n\`)\n\n\`LostI18nProvider\`, \`useLostTranslation\`, \`translate\`, \`registerMessages\`, \`lostI18n\`.\n`;
writeFileSync("skills/lost-ui/references/catalog.md", catalog);

let total = 0;
for (const [layer, dir] of Object.entries(layers)) {
  let out = `# API: ${layer} (\`@danielsoaresf/lost-ui/${layer}\`)\n\nGenerated by \`npm run skill\` from the code. Only the props the component declares are listed; it also accepts the HTML attributes of its root element unless noted. Each folder has a story with working examples.\n\n`;
  for (const folder of entries(layer, dir)) {
    const file = `${dir}/${folder}/${folder.split("/").pop()}.tsx`;
    if (!existsSync(file)) continue;
    let docs = [];
    try {
      docs = parser.parse(file);
    } catch (error) {
      console.warn(`skipped ${file}: ${error.message}`);
      continue;
    }
    for (const doc of docs) {
      if (!/^[A-Z]/.test(doc.displayName) || doc.displayName.endsWith("Context")) continue;
      total++;
      const props = Object.values(doc.props).sort(
        (a, b) => Number(b.required) - Number(a.required),
      );
      out += `## ${doc.displayName}\n\n\`import { ${doc.displayName} } from "@danielsoaresf/lost-ui/${layer}/${folder}";\`\n\n`;
      if (doc.description) out += `${doc.description.trim()}\n\n`;
      if (props.length === 0) {
        out += "_No props of its own._\n\n";
        continue;
      }
      out += "| Prop | Type | Default | Description |\n| --- | --- | --- | --- |\n";
      for (const prop of props) {
        const name = prop.required ? `**${prop.name}**` : prop.name;
        out += `| ${name} | \`${cell(prop.type?.name, 70)}\` | ${prop.defaultValue ? `\`${cell(prop.defaultValue.value, 30)}\`` : ""} | ${cell(prop.description)} |\n`;
      }
      out += "\n";
    }
  }
  writeFileSync(`skills/lost-ui/references/api/${layer}.md`, out);
}
console.log(`api: ${total} components in ${Object.keys(layers).length} layers`);

// keep the generated files in the format `npm run format:check` expects
execFileSync("npx", ["prettier", "--write", "skills"], { stdio: "ignore", shell: true });
