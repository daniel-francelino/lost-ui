import { TrendingUp } from "lucide-react";

import {
  Card,
  CardContent,
  CardDescription,
  CardFooter,
  CardHeader,
  CardTitle,
} from "../../../ui/card";
import type { ChartConfig } from "../../chart-container";
import { seriesFromConfig } from "../../chart-series";
import { RadialChart } from "../radial-chart";

const chartData = [{ month: "january", mobile: 570, desktop: 1260 }];

const chartConfig = {
  desktop: {
    label: "Desktop",
    color: "var(--chart-1)",
  },
  mobile: {
    label: "Mobile",
    color: "var(--chart-2)",
  },
} satisfies ChartConfig;

const totalVisitors = (chartData[0]?.desktop ?? 0) + (chartData[0]?.mobile ?? 0);

const series = [...seriesFromConfig(chartConfig)].reverse();

export function ChartRadialStacked() {
  return (
    <Card className="flex flex-col">
      <CardHeader className="items-center pb-0">
        <CardTitle>Radial Chart - Stacked</CardTitle>
        <CardDescription>January - June 2024</CardDescription>
      </CardHeader>
      <CardContent className="flex flex-1 items-center pb-0">
        <RadialChart
          data={chartData}
          series={series}
          endAngle={180}
          innerRadius={80}
          outerRadius={110}
          centerLabel={{ value: totalVisitors, caption: "Visitors" }}
          tooltipProps={{ hideLabel: true }}
        />
      </CardContent>
      <CardFooter className="flex-col gap-2 text-sm">
        <div className="flex items-center gap-2 leading-none font-medium">
          Trending up by 5.2% this month <TrendingUp className="h-4 w-4" />
        </div>
        <div className="leading-none text-muted-foreground">
          Showing total visitors for the last 6 months
        </div>
      </CardFooter>
    </Card>
  );
}
